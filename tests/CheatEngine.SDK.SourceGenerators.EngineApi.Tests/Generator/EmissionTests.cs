        Assert.Contains(
            "return new global::CheatEngine.SDK.Engine.Values.Address(unchecked((ulong)__engineApiRawResult));",
            text, StringComparison.Ordinal);
        Assert.DoesNotContain("public static nuint", text, StringComparison.Ordinal);
    }

    /// <summary>Address arguments and results retain their strong target-address contract in the public signature.</summary>
    [Fact]
    public void Address_arguments_and_try_results_keep_the_complete_public_signature_strongly_typed()
    {
        const string Text =
            "namespace: Demo\ntype: Addresses\n\nglobal: resolvePointer\nmethod: TryResolvePointer\nform: try\narg: address:address\nresult: result:address\ndoc: Resolves a target pointer.\n";

        var run = roslyn.Run("address-argument-and-result.cheatengine-sdk-api.txt", Text);

        run.AssertCompilesClean();
        var text = run.SingleGeneratedText;
        Assert.Contains(
            "public static bool TryResolvePointer(global::CheatEngine.SDK.Engine.Values.Address address, out global::CheatEngine.SDK.Engine.Values.Address result)",
            text, StringComparison.Ordinal);
        Assert.DoesNotContain("public static bool TryResolvePointer(nuint", text, StringComparison.Ordinal);
        Assert.Contains("unchecked((nuint)address.ToUInt64())", text, StringComparison.Ordinal);
    }

    private static int CountOccurrences(string text, string value)
    {
        var count = 0;
        var index = 0;
        while ((index = text.IndexOf(value, index, StringComparison.Ordinal)) >= 0)
        {
            count++;
            index += value.Length;
        }

        return count;
    }

    // The method sits two levels deep (namespace, then the partial class): 8 spaces, SourceWriter's convention.
    private static string Indented(string text)
    {
        return string.Join('\n',
            text.ReplaceLineEndings("\n").Split('\n')
                .Select(static line => line.Length > 0 ? "        " + line : line));
    }
}
